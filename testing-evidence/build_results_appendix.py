"""Builds documentation/testing/SE3110_Executed_Test_Results.md from the raw tool output.

Nothing here is typed by hand: every row comes from a machine-readable result file produced by the
test tool itself (xUnit .trx, pytest -v, Vitest JSON, flutter test --machine, Playwright JUnit).
Re-run after re-running the suites:   python testing-evidence/build_results_appendix.py
"""
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUN = ROOT / "testing-evidence" / "run-2026-10-07"
OUT = ROOT / "documentation" / "testing" / "SE3110_Executed_Test_Results.md"


def mark(outcome: str) -> str:
    return "Passed" if outcome.lower() in ("passed", "pass") else "Failed" if outcome.lower() in ("failed", "fail") else outcome


def trx_rows(path: Path):
    ns = {"t": "http://microsoft.com/schemas/VisualStudio/TeamTest/2010"}
    root = ET.parse(path).getroot()
    classes = {}
    for ut in root.iterfind(".//t:UnitTest", ns):
        tm = ut.find("t:TestMethod", ns)
        classes[ut.get("id")] = tm.get("className") if tm is not None else "?"
    rows = []
    for r in root.iterfind(".//t:UnitTestResult", ns):
        full = classes.get(r.get("testId"), "?")
        name = r.get("testName")
        if name.startswith(full + "."):  # keep decimals/dots inside parameter values intact
            name = name[len(full) + 1:]
        rows.append((full.split(".")[-1], name, mark(r.get("outcome"))))
    return rows


def pytest_rows(path: Path):
    rows = []
    for line in path.read_text(encoding="utf8", errors="replace").splitlines():
        m = re.match(r"^tests/(\S+?)::(.+?)\s+(PASSED|FAILED|ERROR|SKIPPED)(?:\s|$)", line)
        if m:
            rows.append((m.group(1), m.group(2), mark(m.group(3))))
    return rows


def vitest_rows(path: Path):
    data = json.loads(path.read_text(encoding="utf8"))
    rows = []
    for f in data["testResults"]:
        name = Path(f["name"]).name
        for a in f["assertionResults"]:
            rows.append((name, a["fullName"], mark(a["status"])))
    return rows


def flutter_rows(path: Path):
    starts, rows = {}, []
    for line in path.read_text(encoding="utf8", errors="replace").splitlines():
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        if not isinstance(ev, dict):
            continue
        if ev.get("type") == "testStart" and not ev["test"].get("name", "").startswith("loading "):
            t = ev["test"]
            starts[t["id"]] = (Path(t.get("url", "") or "").name or "?", t["name"])
        elif ev.get("type") == "testDone" and ev.get("testID") in starts and not ev.get("hidden"):
            f, n = starts[ev["testID"]]
            rows.append((f, n, "Passed" if ev["result"] == "success" else "Failed"))
    return rows


def junit_rows(path: Path):
    root = ET.parse(path).getroot()
    rows = []
    for tc in root.iter("testcase"):
        failed = tc.find("failure") is not None or tc.find("error") is not None
        rows.append((tc.get("classname", "").split("\\")[-1].split("/")[-1], tc.get("name"), "Failed" if failed else "Passed"))
    return rows


SUITES = OrderedDict([
    ("Backend: xUnit (unit, service, API integration, concurrency; real PostgreSQL)", ("full-suite-after-fixes.trx", trx_rows)),
    ("Agentic AI: pytest", ("agentic-ai-pytest.txt", pytest_rows)),
    ("Web components: Vitest + React Testing Library", ("web-vitest-results.json", vitest_rows)),
    ("Web end-to-end: Playwright (Chromium)", (ROOT / "testing-evidence" / "web" / "playwright-junit.xml", junit_rows)),
    ("Mobile: flutter_test", ("mobile-flutter-results.jsonl", flutter_rows)),
])


def main():
    lines = [
        "# SE3110: Executed Automated Test Results (generated)",
        "",
        "Generated by `testing-evidence/build_results_appendix.py` from the raw tool output in "
        "`testing-evidence/run-2026-10-07/`. Every row is a test that was actually executed on 2026-10-07; "
        "nothing is typed by hand.",
        "",
    ]
    summary = []
    for title, (src, fn) in SUITES.items():
        p = src if isinstance(src, Path) else RUN / src
        rows = fn(p)
        passed = sum(1 for r in rows if r[2] == "Passed")
        summary.append((title, len(rows), passed, len(rows) - passed, p.relative_to(ROOT).as_posix()))
        lines += [f"## {title}", "", f"Source: `{p.relative_to(ROOT).as_posix()}`. {len(rows)} executed, {passed} passed, {len(rows) - passed} failed.", "",
                  "| # | Group | Test | Result |", "|---:|---|---|---|"]
        for i, (g, n, r) in enumerate(sorted(rows, key=lambda x: (x[0], x[1])), 1):
            lines.append(f"| {i} | {g} | {n.replace('|', '/')} | {r} |")
        lines.append("")
    head = ["## Summary", "", "| Suite | Executed | Passed | Failed | Source |", "|---|---:|---:|---:|---|"]
    head += [f"| {t} | {n} | {p} | {f} | `{s}` |" for t, n, p, f, s in summary]
    tot = [sum(x[i] for x in summary) for i in (1, 2, 3)]
    head += [f"| **Total** | **{tot[0]}** | **{tot[1]}** | **{tot[2]}** | |", ""]
    lines[5:5] = head
    OUT.write_text("\n".join(lines), encoding="utf8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    for s in summary:
        print(s[:4])


if __name__ == "__main__":
    sys.exit(main())
